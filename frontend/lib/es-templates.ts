export const ES_GUIDES: Record<EsQuestionType, EsGuide> = {
  志望動機: MOTIVATION,
  自己PR: SELF_PR,
  学チカ: GAKUCHIKA,
  ガクチカ: GAKUCHIKA,
  その他: OTHER,
}

/** 設問の種類のガイド。知らない種類は「その他」 */
export function guideFor(questionType: string): EsGuide {
  return ES_GUIDES[questionType as EsQuestionType] ?? OTHER
}

/** ガイドの例文の絞り込みの値（並びは例文の順） */
export function exampleTags(guide: EsGuide): string[] {
  return [...new Set(guide.examples.map((e) => e.tag))]
}

/**
 * 入力欄にひな形・例文を入れた結果。空なら置き換え、書きかけなら末尾に足す（書いた文章を消さない）。
 * 上限を超えるなら null（入れない）。
 */
export function insertIntoDraft(current: string, text: string, maxLength: number): string | null {
  const next = current.trim() === '' ? text : `${current.replace(/\s+$/, '')}\n\n${text}`
  return next.length > maxLength ? null : next
}
