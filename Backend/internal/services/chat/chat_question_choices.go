// 軸が分からないときの一般尺度。度合い順なので採点の前提は崩れない。
var choiceScaleDefault = []string{
	"とても当てはまる",
	"まあ当てはまる",
	"あまり当てはまらない",
	"まったく当てはまらない",
}

// 事前定義質問は「経験はありますか／どんな工夫をしましたか」のように、
// 自由記述を前提にした書き方をしている。そこへ度合いの選択肢だけを足すと、
// 何について選ぶのかが曖昧になる（経験を聞かれたのに傾向を選ばされる）。
// 選ぶ対象を一行で言い直してから並べる。
const choiceLeadIn = "この中で、あなたに一番近いものを選んでください。"

// otherChoiceText は最後に置く自由記述。
// ResolveChoiceAnswer が「その他」を記号採点から外して文章採点へ回すので、
// 末尾（最低点の位置）に置いても度合いとしては採点されない。
const otherChoiceText = "その他（自由記述）"

// buildChoiceFallback は選択肢の無い質問に、その質問の評価軸に沿った度合いの
// 選択肢を付ける。category が分からないときだけ一般尺度に落ちる。
func buildChoiceFallback(questionText, category string) string {
	scale, ok := choiceScaleByCategory[strings.TrimSpace(category)]
	if !ok {
		scale = choiceScaleDefault
	}

	lines := make([]string, 0, len(scale)+1)
	for i, text := range scale {
		lines = append(lines, fmt.Sprintf("%d) %s", i+1, text))
	}
	lines = append(lines, fmt.Sprintf("%d) %s", len(scale)+1, otherChoiceText))

	return fmt.Sprintf("%s\n\n%s\n%s", strings.TrimSpace(questionText), choiceLeadIn, strings.Join(lines, "\n"))
}
