//
// これには二つ問題があった。
//
//  1. フェーズは3〜4問続くので、質問が変わっても選択肢が一字一句同じまま並び、
//     画面上は選択肢が更新されていないように見えた。
//  2. 並列な分類に度合いの採点を当てるので、「人と関わりながら進める」を選ぶと
