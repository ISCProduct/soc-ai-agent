// Package masking は学習データの書き出し前に、面接の発話から個人を特定できる語を
// 置き換える前処理を提供する（#2168。設計は #1834 の 7.）。
//
// DB・HTTP には依存しない。呼び出し側（書き出しジョブ）が既知の名称の辞書を用意して
// New で Masker を作り、発話ごとに Mask を呼ぶ。
//
// # 照合の方法
//
// 項目（Rule）ごとに「置き換えの記号」と「辞書による照合か正規表現か」を持つ。
// 項目を足すときは DefaultRules に定義を1つ足すだけでよい。漏れの検査のテストは
// DefaultRules を回すので、足した項目は自動でテストの対象になる（例文が無ければテストが落ちる）。
//
//   - 氏名・学校名・企業名：DB の既知の名称との突き合わせ（辞書）。全角半角・大文字小文字・
//     空白と中黒の有無・ゼロ幅の文字・結合文字の書き方（合成済みの「é」と「e」＋結合用のアクセント）の揺れは吸収する。
//     ラテン文字の名称は単語の途中には一致させない（「Éric」は「Frédéric」に一致しない）。長い名称を優先する（「東京大学大学院」が
//     「<SCHOOL>大学院」にならないように）。
//   - メールアドレス・電話番号・住所：正規表現。誤検出と見落としの判断は rules.go の各パターンに書いた。
//
// 複数の項目の一致が重なったときは、先に始まるもの → 長いもの → DefaultRules で先の項目、の順で採る。
// 置き換えは元の文字列の位置に対して1回で行うので、置き換えた記号（<EMAIL> など）が
// 別の項目に再び一致することはない。
//
// # 辞書の限界と、抜き取り確認の手順
//
// 辞書は既知の名称にしか効かない。辞書に無い氏名（面接中に話した友人の名前など）、
// 1文字の名称（姓が「林」など。誤って本文を壊すので照合しない）、ひらがなとカタカナの
// 書き分け（「やまだ」と「ヤマダ」は別の名称として辞書に入れる必要がある）、
// 略称（「株式会社サンプル」に対する「サンプル」）は、呼び出し側が辞書に入れない限り残る。
// そのため、書き出しのたびに次の抜き取り確認を併用する。
//
//  1. 書き出した JSONL から、無作為に 50 件（全体が 50 件未満なら全件）を選ぶ。
//  2. 確認者（管理者ロールの担当者）が発話を読み、置き換えの記号以外に個人を特定できる語
//     （氏名・学校名・企業名・メールアドレス・電話番号・住所）が残っていないかを見る。
//  3. 残っていた語は、種類ごとに次のどれで防ぐかを決める。
//     辞書に足す（呼び出し側の名称の集め方を直す）／ DefaultRules に項目を足す／
//     正規表現を直す。直したら、その語を含む例文をテストに足す。
//  4. 残りがあった回の書き出しは学習に使わず、直してから書き出し直す。
//  5. 確認した日・件数・見つかった語の種類（語そのものは書かない）を記録する。
