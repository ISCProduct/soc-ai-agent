// 内容語抽出そのものを固定する（#1566）。
// ここが変わると ContentBestMatch の分布ごと動くので、代表例を押さえておく。
func TestContentRunes(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		in   string
		want string
	}{
		{"助詞・活用語尾が落ちる", "部員数を3倍にすることができました", "部員数3倍"},
		{"述語末尾だけの流用は内容語が残る", "国際特許を3件取得することができました", "国際特許3件取得"},
		{"カタカナと英数は残る", "SNSでの告知を担当しました", "sns告知担当"},
		{"長音符は落ちる（needle/haystack で同じ扱い）", "軽音サークルの代表", "軽音サクル代表"},
		{"全角数字はNFKCで半角になる", "２３人まで増えて", "23人増"},
		{"相槌は何も残らない", "えー、その、あ", ""},
		{"はいは何も残らない", "はい", ""},
		{"ひらがなだけの内容語も落ちる", "おもてなしを心がけました", "心"},
		{"記号だけは何も残らない", "。。。！？🎉", ""},
		{"空文字", "", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := ContentRunes(tt.in); got != tt.want {
				t.Errorf("ContentRunes(%q) = %q, want %q", tt.in, got, tt.want)
			}
		})
	}
}

// ContentBestMatch の実測値を固定する（#1566）。
//
// 呼び出し側のしきい値（interview の EvidenceMatchThreshold = 0.25）は、
// ここで測った分布から決めている。値が動いたら
// docs/wiki/scoring.md §2-4 と interview_rubric.go の実測表も引き直すこと。
//
// クラスごとの範囲（この表の実測値より）:
//
//	正当（引用・表記ゆれ・助詞違い）  1.00
//	正当（要約・言い換え）            0.29〜1.00
//	捏造（実引用＋継ぎ足し）          0.35〜0.36  ← 通ってしまう（既知の限界）
//	捏造（述語末尾だけを流用）        0.00〜0.14
//	捏造（述語も流用しない）          0.00〜0.13
//	相槌・フィラー                    0.00
func TestContentBestMatch_PinnedScores(t *testing.T) {
	t.Parallel()

	spoken := NewContent(`はい、私は大学時代に軽音サークルの代表を務めていました。
入学した当初は部員が8人しかいなくて、このままだと廃部になるという話が出ていました。
そこで私が新歓ライブの企画を提案して、SNSでの告知を担当しました。
結果として、翌年の新入部員は23人まで増えて、部員数を3倍にすることができました。
えー、その、あ、すみません、言い直します。プログラミングは独学で、毎日2時間くらい続けています。`)

	tests := []struct {
		class  string
		needle string
		want   float64
	}{
		// 正当な根拠
		{"正当・引用そのまま", "結果として、翌年の新入部員は23人まで増えて、部員数を3倍にすることができました。", 1},
		{"正当・引用そのまま", "私が新歓ライブの企画を提案して", 1},
		{"正当・表記ゆれ", "翌年の新入部員は２３人まで増えて 部員数を３倍にすることができました", 1},
		{"正当・助詞違い", "私が新歓ライブの企画も提案し、SNSでの告知も担当しました", 1},
		{"正当・言い直しを除いた引用", "プログラミングは独学で毎日2時間続けている", 1},
		{"正当・要約", "新歓ライブを企画してSNS告知を担当し、部員数を3倍にした", 0.6667},
		{"正当・要約", "部員が8人から23人に増えた", 0.6154},
		{"正当・要約", "軽音サークルの代表を務めた", 1},
		{"正当・要約", "新入部員が23人になった", 1},
		// 帯の上限側（これが落ちるとしきい値が厳しすぎる）
		{"正当・要約(最低)", "廃部の危機にあった軽音サークルを立て直した", 0.4000},
		{"正当・要約(最低)", "自分から提案した", 0.3333},
		// 捏造: 述語末尾だけを流用（#1566 クラス1）。全文bigramでは 0.27〜0.56 に乗っていた
		{"捏造・述語流用", "国際特許を3件取得することができました", 0},
		{"捏造・述語流用", "学部長賞の選考を担当しました", 0.1429},
		{"捏造・述語流用", "宇宙飛行士の訓練を修了することができました", 0},
		{"捏造・述語流用", "投資ファンドの運用を担当しました", 0.1111},
		{"捏造・述語流用", "日経新聞の連載を担当しました", 0.1429},
		{"捏造・述語流用", "創薬の基礎研究に従事することができました", 0},
		{"捏造・述語流用", "国体の強化選手に選ばれることができました", 0},
		{"捏造・述語流用", "為替ディーリングの実務を担当しました", 0.1},
		{"捏造・述語流用", "重機の整備資格を取得することができました", 0},
		{"捏造・述語流用", "病院の会計監査を担当しました", 0.1429},
		{"捏造・述語流用", "観光協会の広報誌を担当しました", 0.125},
		// 捏造: 述語も流用しない
		{"捏造・流用なし", "TOEICで900点を取得し、英語での商談経験もあります。", 0},
		{"捏造・流用なし", "ラグビー日本代表に選出されました", 0.125},
		{"捏造・流用なし", "高校時代は野球部でキャプテンを務め、県大会でベスト8に入りました。", 0.05},
		// 相槌・フィラー（#1566 クラス2）。全文bigramでは部分文字列なので 1.00 だった
		{"相槌", "はい", 0},
		{"相槌", "すみません", 0},
		{"相槌", "えー、その、あ", 0},
		{"相槌", "はい、わかりました", 0},
		{"相槌", "なるほど", 0},
		// 内容語1文字は bigram が作れないので照合しない
		{"退化", "私", 0},
		{"退化", "その、私が", 0},
		{"退化", "3", 0},
		// 既知の限界: 内容語を流用した捏造は正当な要約と同じ帯に入る（Issue #1566 に残す）
		{"既知の限界・継ぎ足し", "入学した当初は部員が8人しかいなくて、私が部長として3年間で部員数を50人まで増やしました", 0.3590},
		{"既知の限界・継ぎ足し", "部員が8人から100人に増えて、部費を3倍にすることができました", 0.3478},
	}
	for _, tt := range tests {
		t.Run(tt.class+"/"+tt.needle, func(t *testing.T) {
			t.Parallel()
			if got := ContentBestMatch(tt.needle, spoken); math.Abs(got-tt.want) > 0.0001 {
				t.Errorf("ContentBestMatch = %.4f, want %.4f", got, tt.want)
			}
		})
	}
}

// クラスとしての分離を固定する（#1566）。
// 「述語を流用しただけの捏造」と「相槌」がしきい値 0.25 の下に落ちること、
// 正当な根拠がその上に残ることを、1件ずつではなく群として押さえる。
// 発話は TestContentBestMatch_PinnedScores と別の話題にして、
// 特定の発話に依存した結果でないことを確かめる。
func TestContentBestMatch_ClassSeparation(t *testing.T) {
	t.Parallel()

	spoken := NewContent(`はい、私は二年間コンビニでアルバイトをしていました。
最初はレジ打ちだけでしたが、途中から発注も任されるようになりました。
廃棄が多いことが気になっていたので、売れ残りの記録をノートに付けて、
発注の数を曜日ごとに変えることを店長に提案しました。
その結果、廃棄のロスを半年で三割ほど減らすことができました。
あと、資格は日商簿記の2級を持っています。独学で半年ほど勉強しました。`)

	// しきい値の上に残るべきもの（正当な根拠）
	valid := []string{
		"二年間コンビニでアルバイトをしていました",
		"最初はレジ打ちだけでしたが、途中から発注も任されるようになりました",
		"発注の数を曜日ごとに変えることを店長に提案しました",
		"廃棄のロスを半年で三割ほど減らすことができました",
		"資格は日商簿記の2級を持っています",
		"売れ残りの記録をノートに付けて",
		"独学で半年ほど勉強しました",
		"売れ残りを記録して曜日ごとに発注数を変えることを店長に提案した",
		"廃棄ロスを半年で三割減らした",
		"コンビニのアルバイトで発注を任された",
		"日商簿記2級を独学で取得した",
		"廃棄が多いという課題に気づいて記録を付けた",
		"レジ打ちから発注まで担当範囲が広がった",
		"半年で廃棄を3割削減できた",
	}
	// しきい値の下に落ちるべきもの（内容語を流用していない捏造）
	fabricated := []string{
		"クレーム対応のマニュアル作成を任されるようになりました",
		"英検の準1級を持っています",
		"深夜帯のシフト管理を任されるようになりました",
		"レジ締めの不一致をゼロにすることができました",
		"本社のコンテストで入賞することができました",
		"食品衛生責任者の資格を持っています",
		"品出しの時間を半分に短縮することができました",
		"新人教育の担当を任されるようになりました",
		"来客数を三割ほど増やすことができました",
		"公認会計士の勉強を独学で続けました",
		"大学では量子力学の研究室に所属していました",
		"サッカー部で県選抜に選ばれました",
		"家庭教師として5名の生徒を志望校に合格させました",
		"軽音サークルの代表を務めていました",
	}
	// 相槌・フィラー（内容語が残らないので必ず 0）
	fillers := []string{
		"はい", "えーと、あの", "すみません", "そうですね", "はい、あと",
		"うーん", "ちょっと", "なるほど", "そうです", "えー", "あの、はい", "ええ、はい",
	}

	// interview の EvidenceMatchThreshold と同じ値。
	// こちらは textsim 側の下限として独立に固定する（パッケージ参照を作らない）。
	const threshold = 0.25

	lowestValid := 1.0
	for _, s := range valid {
		got := ContentBestMatch(s, spoken)
		lowestValid = min(lowestValid, got)
		if got < threshold {
			t.Errorf("正当な根拠が落ちた: %.4f  %s", got, s)
		}
	}
	highestFabricated := 0.0
	for _, s := range fabricated {
		got := ContentBestMatch(s, spoken)
		highestFabricated = max(highestFabricated, got)
		if got >= threshold {
			t.Errorf("内容語を流用していない捏造が通った: %.4f  %s", got, s)
		}
	}
	for _, s := range fillers {
		if got := ContentBestMatch(s, spoken); got != 0 {
			t.Errorf("相槌が 0 にならない: %.4f  %s", got, s)
		}
	}
	// 実測の帯（0.2222〜0.2857）。狭まったらしきい値の置き場所を見直すこと
	t.Logf("正当の最低=%.4f / 捏造の最高=%.4f (n=%d/%d/%d)",
		lowestValid, highestFabricated, len(valid), len(fabricated), len(fillers))
	if lowestValid <= highestFabricated {
		t.Errorf("クラスが分離できていない: 正当の最低 %.4f <= 捏造の最高 %.4f", lowestValid, highestFabricated)
	}
}

// 内容語照合でも空・不正な入力は照合成功にしないこと。
func TestContentBestMatch_EmptyIsNotAMatch(t *testing.T) {
	t.Parallel()

	hay := NewContent("部員数を3倍にしました")
	tests := []struct {
		name     string
		needle   string
		haystack Bigrams
	}{
		{"needle が空", "", hay},
		{"needle が記号だけ", "。。。！？", hay},
		{"needle がひらがなだけ", "そうしました", hay},
		{"needle の内容語が1文字", "部", hay},
		{"haystack が空", "部員数を3倍にした", NewContent("")},
		{"haystack がひらがなだけ", "部員数を3倍にした", NewContent("そうですね、はい")},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := ContentBestMatch(tt.needle, tt.haystack); got != 0 {
				t.Errorf("ContentBestMatch = %v, want 0", got)
			}
		})
	}
}
